import { BinaryTransport } from "../transport";

/** Repository object key, as in E071. */
export type DeletionObject = { pgmid: string, object: string, objName: string };

/** Customizing key: a key (`TABKEY`, client included) of a table (E071K `OBJNAME`). */
export type DeletionKey = { table: string, tabkey: string };

/**
 * Options of a deletion transport request. The uploaded transport (a backup of what is installed) is turned
 * into a deletion of its content minus `subtract` and `exclude`.
 */
export type DeleteTransportOptions = {
    /** Request the deletion transport is renamed to (a dummy created on the system). Default: the uploaded request. */
    target?: string,
    /** Registry transports (of the incoming release) whose objects and customizing keys are never deleted. */
    subtract?: string[],
    /** Objects and customizing keys never deleted. */
    exclude?: {
        e071?: DeletionObject[],
        e071k?: DeletionKey[]
    }
};

/** Deletion transport generated by the registry. */
export type DeletionTransport = {
    /** Nothing is left to delete: no binaries. */
    empty: boolean,
    binaries?: BinaryTransport,
    /** What the deletion transport deletes, when the registry reports it. */
    deleted?: {
        e071: DeletionObject[],
        e071k: DeletionKey[]
    }
};
