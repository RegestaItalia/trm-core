import * as AdmZip from 'adm-zip';
import { Readable } from 'stream';
import { Logger } from 'trm-commons';
import { RegistryV2 } from './RegistryV2';

describe('registry package download', () => {
    let get: jest.Mock;

    function registry(): RegistryV2 {
        const registry = new RegistryV2('http://localhost/registry', 'test');
        (registry as any)._axiosInstance = { get };
        return registry;
    }

    function packageResponse(link: string) {
        return { status: 200, data: { download_link: link } };
    }

    const zip = new AdmZip.default();
    zip.addFile('content', Buffer.from('artifact'));
    const artifactBinary = zip.toBuffer();

    function artifactResponse() {
        return { status: 200, headers: {}, data: Readable.from([artifactBinary]) };
    }

    function statusError(status: number) {
        return Object.assign(new Error(`Request failed with status code ${status}`), { response: { status } });
    }

    beforeEach(() => {
        get = jest.fn();
        for (const method of ['log', 'error', 'warning'] as const) {
            jest.spyOn(Logger, method).mockImplementation(() => undefined as never);
        }
        jest.spyOn(Logger, 'progressbar').mockReturnValue({ start: jest.fn(), update: jest.fn(), stop: jest.fn() } as any);
    });

    afterEach(() => {
        jest.restoreAllMocks();
    });

    test('a gone link is regenerated by viewing the package again', async () => {
        get.mockImplementation(async (url: string) => {
            if (url === '/package/pkg') {
                return get.mock.calls.filter(c => c[0] === '/package/pkg').length === 1
                    ? packageResponse('http://dl/old')
                    : packageResponse('http://dl/new');
            }
            if (url === 'http://dl/old') {
                throw statusError(410);
            }
            return artifactResponse();
        });

        const artifact = await registry().downloadArtifact('pkg', '1.0.0');

        expect(artifact.binary.equals(artifactBinary)).toBe(true);
        expect(get.mock.calls.map(c => c[0])).toEqual(['/package/pkg', 'http://dl/old', '/package/pkg', 'http://dl/new']);
    });

    test('a link gone again after the refresh fails', async () => {
        get.mockImplementation(async (url: string) => {
            if (url === '/package/pkg') {
                return packageResponse('http://dl/link');
            }
            throw statusError(410);
        });

        await expect(registry().downloadArtifact('pkg', '1.0.0')).rejects.toThrow('410');
        expect(get.mock.calls.map(c => c[0])).toEqual(['/package/pkg', 'http://dl/link', '/package/pkg', 'http://dl/link']);
    });

    test.each([401, 403, 404, 500])('a %i download error is not retried', async (status) => {
        get.mockImplementation(async (url: string) => {
            if (url === '/package/pkg') {
                return packageResponse('http://dl/link');
            }
            throw statusError(status);
        });

        await expect(registry().downloadArtifact('pkg', '1.0.0')).rejects.toThrow(String(status));
        expect(get.mock.calls.map(c => c[0])).toEqual(['/package/pkg', 'http://dl/link']);
    });
});
