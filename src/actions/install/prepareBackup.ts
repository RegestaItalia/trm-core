import { Step } from "@simonegaffurini/sammarksworkflow";
import { InstallWorkflowContext } from ".";
import { Logger } from "trm-commons";
import { TADIR } from "../../client";
import { Transport } from "../../transport";
import { stopWarning } from "../stopWarning";
import { backupInstalledPackage, deleteCleanupStagingPackages, restoreTadirAssignments, withScopedPrefix } from "../commons/utils";
import { findExistingObjects } from "./checkTransports";

function entryKey(entry: { pgmid: string, object: string, objName: string }): string {
    return `${entry.pgmid.trim().toUpperCase()} ${entry.object.trim().toUpperCase()} ${entry.objName.trim().toUpperCase()}`;
}

/**
 * Objects of the incoming release (SAP packages, objects, translations) that are already on the system: the
 * import overwrites them, so a rollback restores them instead of deleting them. Objects generated by this
 * install are left out; objects of temporary packages can't be exported and keep their imported version.
 */
async function findOverwrittenObjects(context: InstallWorkflowContext): Promise<TADIR[]> {
    const generated = new Set([
        ...context.revert.sapPackages.map(devclass => entryKey({ pgmid: 'R3TR', object: 'DEVC', objName: devclass })),
        ...(context.revert.namespace ? [entryKey({ pgmid: 'R3TR', object: 'NSPC', objName: context.revert.namespace })] : [])
    ]);
    const transports = [context.runtime.transports.devc, context.runtime.transports.tadir, context.runtime.transports.lang].filter(Boolean);
    const candidates = new Map(transports.flatMap(o => o.binaries?.entries?.e071 || [])
        .filter(entry => entry.pgmid.trim().toUpperCase() === 'R3TR' && !generated.has(entryKey(entry)))
        .map(entry => [entryKey(entry), { pgmid: entry.pgmid, object: entry.object, objName: entry.objName, devclass: '' }]));
    if (candidates.size === 0) {
        return [];
    }
    Logger.loading(`Checking existing objects...`, true);
    const existing = (await findExistingObjects(context, Array.from(candidates.values())))
        .filter(object => candidates.has(entryKey(object)));
    // Tracked before the backup: even without one, the rollback must not delete them.
    context.revert.existingObjectsTadir = existing.map(object => ({ ...object }));
    return existing.filter(object => {
        if (!(object.devclass || '').trim().startsWith('$')) {
            return true;
        }
        Logger.warning(`${object.pgmid} ${object.object} ${object.objName} (temporary SAP package ${object.devclass}) can't be backed up: a rollback keeps its imported version.`, { important: true });
        return false;
    });
}

/**
 * Workflow step that backs up, before anything is imported or deleted:
 * - on upgrade, what the cleanup planned by plan-update-cleanup may delete (installed objects and customizing);
 * - the objects of the incoming release already on the system, overwritten by the import.
 *
 * The backups are released transports of copies kept in the import queue: a rollback re-imports them, and
 * they stay there afterwards for a manual recovery.
 */
export const prepareBackup: Step<InstallWorkflowContext> = {
    name: 'prepare-backup',
    run: async (context: InstallWorkflowContext): Promise<void> => {
        if (!context.runtime.stopWarningShown) {
            context.runtime.stopWarningShown = true;
            stopWarning('install');
        }
        await withScopedPrefix(`(${Transport.getTransportIcon()}  Backup) `, async () => {
            // A trm-server/trm-rest upgrade is never rolled back after its import: only the cleanup needs a backup
            const overwritten = context.runtime.selfUpdate ? [] : await findOverwrittenObjects(context);
            const plan = context.runtime.cleanupPlan;
            await backupInstalledPackage(context, plan, overwritten, {
                packageName: context.rawInput.packageData.name,
                version: plan ? plan.installedVersion : context.runtime.package.data.manifest.version
            });
        });
    },
    revert: async (context: InstallWorkflowContext): Promise<void> => {
        // The backups stay in the import queue. Objects of a temporary installation staged for the
        // backup go back to their packages (after the import, the backups restored them first).
        if (context.revert.importStarted && !context.revert.cleanupSucceeded) {
            return;
        }
        await restoreTadirAssignments(context.revert.cleanupOriginalTadir || []);
        await deleteCleanupStagingPackages(context);
    }
};
