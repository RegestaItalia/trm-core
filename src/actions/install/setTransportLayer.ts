import { Step } from "@simonegaffurini/sammarksworkflow";
import { InstallWorkflowContext } from ".";
import { Inquirer, Logger } from "trm-commons";
import chalk from "chalk";
import { DEVCLASS } from "../../client";
import { SystemConnector } from "../../systemConnector";
import { flattenDevclasses } from "./addNamespace";
import { getDefaultTransportLayer } from "./defaultTransportLayer";
import { lacksTrmBackendApis } from "../commons/utils";

/**
 * Transport layers with a consolidation route from the connected system to `target`, or `undefined`
 * when a trm-server/trm-rest upgrade runs on a backend without the API (the layers are then not checked).
 */
async function getRoutedLayers(context: InstallWorkflowContext, target: string): Promise<string[] | undefined> {
    if (lacksTrmBackendApis(context, 'trmServer8')) {
        Logger.log(`Transport layer routes can't be read on a TRM backend older than trm-server 8.0.0, layers won't be checked`, true);
        return undefined;
    }
    return SystemConnector.getTransportLayers(target);
}

async function readDefaultLayer(): Promise<string | undefined> {
    try {
        return await getDefaultTransportLayer();
    } catch (e) {
        Logger.log(`${e}`, true);
        return undefined;
    }
}

/**
 * Workflow step that sets the transport layer of the SAP packages created (renamed) or imported
 * (original names) without one by the install, before anything is locked or changed.
 * 
 * The landscape transport is released to the landscape target: a package can be recorded in it only when
 * its transport layer routes to that target.
 * 
 * 1- find the install packages that need a transport layer, and check the layer of the existing ones
 * 
 * 2- resolve the transport layer: the input layer, the only routed layer, or the user's choice
 * 
 * Without a landscape target, or when a trm-server/trm-rest upgrade runs on a backend without the routes
 * API, the input layer or the system default is used, unchecked.
 * 
*/
export const setTransportLayer: Step<InstallWorkflowContext> = {
    name: 'set-transport-layer',
    run: async (context: InstallWorkflowContext): Promise<void> => {
        const installDevclass = context.rawInput.installData.installDevclass;
        const inputLayer = installDevclass.transportLayer?.trim().toUpperCase();
        const target = context.rawInput.installData.landscapeTransport.targetSystem;

        //1- find the install packages that need a transport layer, and check the layer of the existing ones
        Logger.loading(`Checking transport layer...`);
        const devclasses: DEVCLASS[] = [...new Set(flattenDevclasses(context.runtime.package.hierarchy)
            .map(originalDevclass => installDevclass.keepOriginal ? originalDevclass
                : installDevclass.replacements.find(o => o.originalDevclass === originalDevclass)?.installDevclass || originalDevclass)
            .map(devclass => devclass.trim().toUpperCase()))]
            .filter(devclass => !devclass.startsWith('$'));
        let routedLayers: string[] | undefined;
        let needsLayer = false;
        for (const devclass of devclasses) {
            const existing = await SystemConnector.getDevclass(devclass);
            const layer = existing?.pdevclass?.trim().toUpperCase();
            if (!existing || installDevclass.keepOriginal && (!layer || inputLayer)) {
                //generated by generate-devclass, or imported by the DEVC transport (the input layer replaces the existing one)
                needsLayer = true;
            } else if (layer && target) {
                routedLayers ||= await getRoutedLayers(context, target);
                if (routedLayers && !routedLayers.includes(layer)) {
                    throw new Error(`ABAP package ${devclass} has transport layer ${layer}, which doesn't route to ${target}. Change its transport layer (SE21) or choose another target.`);
                }
            }
        }
        if (!needsLayer) {
            return;
        }

        //2- resolve the transport layer
        if (target) {
            routedLayers ||= await getRoutedLayers(context, target);
        }
        if (!routedLayers) {
            //no landscape transport to release, or routes unknown: input layer, else the system default
            if (inputLayer) {
                context.runtime.transportLayer = inputLayer;
            } else {
                context.runtime.transportLayer = await getDefaultTransportLayer();
                Logger.log(`Setting transport layer to default: ${context.runtime.transportLayer}`, true);
            }
            return;
        }
        if (inputLayer) {
            if (!routedLayers.includes(inputLayer)) {
                throw new Error(`Transport layer ${inputLayer} doesn't route to ${target}${routedLayers.length > 0 ? `, use one of: ${routedLayers.join(', ')}` : ''}.`);
            }
            context.runtime.transportLayer = inputLayer;
            return;
        }
        if (routedLayers.length === 0) {
            throw new Error(`No consolidation route from ${SystemConnector.getDest()} to ${target}: configure one in STMS or choose another target.`);
        }
        if (routedLayers.length === 1) {
            context.runtime.transportLayer = routedLayers[0];
            Logger.info(`Transport layer automatically set to ${chalk.bold(context.runtime.transportLayer)}`);
            return;
        }
        const defaultLayer = await readDefaultLayer();
        const routedDefault = defaultLayer && routedLayers.includes(defaultLayer) ? defaultLayer : undefined;
        if (context.rawInput.contextData.noInquirer) {
            if (!routedDefault) {
                throw new Error(`Transport layer was not declared: use one of ${routedLayers.join(', ')} (routed to ${target}).`);
            }
            context.runtime.transportLayer = routedDefault;
            Logger.log(`Setting transport layer to default: ${context.runtime.transportLayer}`, true);
            return;
        }
        const choices = routedDefault ? [routedDefault, ...routedLayers.filter(layer => layer !== routedDefault)] : routedLayers;
        context.runtime.transportLayer = (await Inquirer.prompt({
            type: "list",
            message: `Transport layer of the new ABAP packages (routed to ${target})`,
            name: "transportLayer",
            choices: choices.map(layer => ({
                name: layer === routedDefault ? `${layer} (default)` : layer,
                value: layer
            }))
        })).transportLayer;
    }
}
